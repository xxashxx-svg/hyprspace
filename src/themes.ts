export function applyTheme(id: string): void {
  const theme = THEMES.find((t) => t.id === id) ?? THEMES[0];
  const root = document.documentElement;
  for (const [k, val] of Object.entries(theme.vars)) {
    root.style.setProperty(k, val);
  }
}
